"""Build docs/traceability-matrix.md from docs/requirements.md and the test traces.

    uv run python scripts/traceability.py      # or: make traceability

The traces are reports/trace-<layer>.json, written by `pytest --trace-out` during
`make regression`. Exits 1 if any requirement has no passing test, or no traces exist.

`--not-run DIR` (from `regression.py --skip`): a requirement whose only tests are in DIR,
a layer left out on purpose, is listed as not run instead of failing the check.
"""

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
REQUIREMENTS = REPO / "docs" / "requirements.md"
MATRIX = REPO / "docs" / "traceability-matrix.md"
TRACES = REPO / "reports"


def load_requirements() -> list[tuple[str, str, str]]:
    """(section, id, text) in document order."""
    section, rows = "", []
    for line in REQUIREMENTS.read_text().splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        match = re.match(r"^\| (REQ-[A-Z0-9-]+) \| (.+) \|$", line)
        if match:
            rows.append((section, match[1], match[2]))
    return rows


def load_traces() -> dict[str, dict[str, str]]:
    merged: dict[str, dict[str, str]] = defaultdict(dict)
    for path in sorted(TRACES.glob("trace-*.json")):
        for req, tests in json.loads(path.read_text()).items():
            for nodeid, outcome in tests.items():
                if merged[req].get(nodeid) != "failed":
                    merged[req][nodeid] = outcome
    return merged


def collapse(tests: dict[str, str]) -> list[tuple[str, int, str]]:
    """Group parametrized variants: (test, variants, worst outcome)."""
    groups: dict[str, list[str]] = defaultdict(list)
    for nodeid, outcome in tests.items():
        groups[nodeid.split("[", 1)[0]].append(outcome)
    rank = {"failed": 0, "skipped": 1, "passed": 2}
    return sorted(
        (name, len(outcomes), min(outcomes, key=lambda o: rank.get(o, 0)))
        for name, outcomes in groups.items()
    )


def marked_in(directories: list[str]) -> set[str]:
    """Requirement IDs named by the tests in these directories."""
    found: set[str] = set()
    for directory in directories:
        for path in (REPO / directory).rglob("*.py"):
            found |= set(re.findall(r"REQ-[A-Z0-9]+-\d+", path.read_text()))
    return found


def status(tests: dict[str, str]) -> str:
    outcomes = set(tests.values())
    if "failed" in outcomes:
        return "**FAILING**"
    if "passed" in outcomes:
        return "covered"
    return "**NOT COVERED**"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build docs/traceability-matrix.md.")
    parser.add_argument("--not-run", action="append", default=[], metavar="DIR")
    not_run_dirs = parser.parse_args(argv).not_run
    requirements = load_requirements()
    traces = load_traces()
    if not traces:
        print("no traces in reports/; run `make regression` first", file=sys.stderr)
        return 1

    git = lambda *args: subprocess.run(  # noqa: E731
        ["git", *args], capture_output=True, text=True, cwd=REPO
    ).stdout.strip()
    commit = git("rev-parse", "--short", "HEAD")
    if git("status", "--porcelain"):
        commit += " plus uncommitted changes"
    statuses = {req: status(traces.get(req, {})) for _, req, _ in requirements}
    for req in marked_in(not_run_dirs):
        if statuses.get(req) == "**NOT COVERED**":
            statuses[req] = "not run (layer skipped)"
    covered = sum(s == "covered" for s in statuses.values())
    not_run = sum(s.startswith("not run") for s in statuses.values())
    test_count = len({n for tests in traces.values() for n in tests})

    lines = [
        "# Traceability matrix",
        "",
        "Generated by `make traceability` from [requirements.md](requirements.md) and the "
        "requirement markers (`@pytest.mark.req`) on the tests, using the outcomes of the "
        f"last `make regression` run (`{commit}`). Do not edit by hand.",
        "",
        f"**{covered} of {len(requirements)} requirements covered by at least one passing "
        f"test**, using {test_count} marked test cases. Parametrized tests are listed once, "
        "with the number of cases."
        + (
            f" {not_run} more are covered only by layers this run left out "
            f"({', '.join(f'`{d}`' for d in not_run_dirs)})."
            if not_run
            else ""
        ),
    ]
    section = None
    for sec, req, text in requirements:
        if sec != section:
            section = sec
            lines += [
                "",
                f"## {sec}",
                "",
                "| Requirement | Status | Tests |",
                "| --- | --- | --- |",
            ]
        tests = collapse(traces.get(req, {}))
        cells = (
            "<br>".join(
                f"`{name.removeprefix('tests/')}`"
                + (f" ×{n}" if n > 1 else "")
                + ("" if outcome == "passed" else f" ({outcome})")
                for name, n, outcome in tests
            )
            or "—"
        )
        lines.append(f"| **{req}** {text} | {statuses[req]} | {cells} |")

    MATRIX.write_text("\n".join(lines) + "\n")
    gaps = [req for req, s in statuses.items() if s != "covered" and not s.startswith("not run")]
    print(
        f"traceability: {covered}/{len(requirements)} requirements covered"
        + (f", {not_run} not run (layers skipped)" if not_run else "")
        + f" -> {MATRIX.relative_to(REPO)}"
    )
    if gaps:
        print("not covered or failing: " + ", ".join(gaps), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
